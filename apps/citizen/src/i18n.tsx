const DICTS: Record<Lang, Record<Key, string>> = { en, bn, hi };
export const LANG_LABELS: Record<Lang, string> = { bn: "বাংলা", en: "English", hi: "हिन्दी" };
const STORAGE_KEY = "hope-lang";

function storedLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "bn" || v === "en" || v === "hi") return v;
  } catch {
    /* storage unavailable */
  }
  return "bn";
}

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  l: (text: LocalizedText | null | undefined) => string;
  time: (iso: string | Date) => string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(storedLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
    setLangState(next);
  }, []);

  const value = useMemo<I18n>(() => ({
    lang,
    setLang,
    t: (key, vars) => (DICTS[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? "")),
    l: (text) => (text ? pickLang(text, lang) : ""),
    time: (iso) =>
      new Date(iso).toLocaleTimeString(lang === "en" ? "en-IN" : `${lang}-IN`, {
        hour: "2-digit", minute: "2-digit", hour12: false, timeZone: "Asia/Kolkata",
      }),
  }), [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
